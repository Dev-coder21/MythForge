import { useCallback, useEffect, useState } from 'react'
import { Link, useParams } from 'react-router'
import { StoryInfoPanel } from '@/components/StoryInfoPanel'
import { api, ApiError, type GroundingReport } from '@/lib/api'
import { usePageMeta } from '@/lib/usePageMeta'
import { NotFound } from '@/pages/NotFound'
import { StoryPage } from '@/pages/StoryPage'
import { STORIES, type StorySpec } from '@/spec'

type State =
  | { status: 'loading' }
  | { status: 'ready'; spec: StorySpec; generated: boolean }
  | { status: 'missing' }
  | { status: 'error'; message: string }

/** /story/:slug: a built-in story (Kyoto, Giza) or one generated by the backend. */
export function StoryRoute() {
  const { slug = '' } = useParams()
  const key = slug.toLowerCase()
  const [state, setState] = useState<State>({ status: 'loading' })
  const [grounding, setGrounding] = useState<GroundingReport | null | 'loading'>(null)
  const [needsPoster, setNeedsPoster] = useState(false)
  const [attempt, setAttempt] = useState(0)

  useEffect(() => {
    let alive = true
    setState({ status: 'loading' })
    setGrounding(null)
    setNeedsPoster(false)
    const local = STORIES[key]
    if (local) {
      void local().then((spec) => alive && setState({ status: 'ready', spec, generated: false }))
      return () => {
        alive = false
      }
    }
    api
      .story(key)
      .then((spec) => {
        if (!alive) return
        setState({ status: 'ready', spec, generated: true })
        setGrounding('loading')
        api
          .grounding(spec.id)
          .then((g) => alive && setGrounding(g))
          .catch(() => alive && setGrounding(null))
        // Take a gallery poster on first view.
        fetch(api.url(`/stories/${spec.id}/poster`))
          .then((r) => alive && setNeedsPoster(r.status === 404))
          .catch(() => undefined)
      })
      .catch((e: unknown) => {
        if (!alive) return
        if (e instanceof ApiError && (e.status === 404 || e.status === 409)) setState({ status: 'missing' })
        else setState({ status: 'error', message: e instanceof Error ? e.message : 'The story could not be loaded.' })
      })
    return () => {
      alive = false
    }
  }, [key, attempt])

  const spec = state.status === 'ready' ? state.spec : null
  usePageMeta(
    spec?.title ?? (state.status === 'missing' ? 'Story not found' : 'Loading story'),
    spec?.subtitle ?? 'A cinematic scroll story made with MythForge.',
  )

  const onPoster = useCallback(
    (dataUrl: string) => {
      if (spec) void api.uploadPoster(spec.id, dataUrl).catch(() => undefined)
    },
    [spec],
  )
  // Dev-only: /story/kyoto?capture-poster saves the featured card frame to .captures/poster-kyoto.jpg
  // (copy it to public/posters/). Built-in stories have no backend record to upload to.
  const devPoster = useCallback(
    (dataUrl: string) => void fetch(`/__capture?name=poster-${key}`, { method: 'POST', body: dataUrl }),
    [key],
  )
  const wantDevPoster = import.meta.env.DEV && new URLSearchParams(window.location.search).has('capture-poster')

  if (state.status === 'missing') return <NotFound slug={key} />
  if (state.status === 'error') return <StoryError message={state.message} onRetry={() => setAttempt((a) => a + 1)} />
  if (state.status === 'loading') return <StorySkeleton />
  return (
    <>
      <StoryPage
        key={key}
        spec={state.spec}
        onPoster={needsPoster ? onPoster : !state.generated && wantDevPoster ? devPoster : undefined}
      />
      <StoryInfoPanel spec={state.spec} grounding={state.generated ? grounding : undefined} />
    </>
  )
}

function StorySkeleton() {
  return (
    <div className="flex min-h-[100svh] flex-col justify-end bg-[#07080c] px-5 pb-20 md:px-16" aria-busy="true" aria-label="Loading story">
      <div className="h-2 w-40 animate-pulse bg-white/10" />
      <div className="mt-5 h-16 w-3/4 max-w-2xl animate-pulse bg-white/10 md:h-24" />
      <div className="mt-6 h-3 w-full max-w-xl animate-pulse bg-white/[0.07]" />
      <div className="mt-3 h-3 w-2/3 max-w-md animate-pulse bg-white/[0.07]" />
    </div>
  )
}

function StoryError({ message, onRetry }: { message: string; onRetry: () => void }) {
  return (
    <main className="flex min-h-[100svh] items-center bg-[#0b0e16] px-6 text-white md:px-16">
      <div className="max-w-xl" role="alert">
        <p className="text-[11px] tracking-[0.3em] text-white/50">STORY · UNAVAILABLE</p>
        <h1 className="mt-4 text-3xl font-normal leading-[1.1] md:text-5xl">This story could not be loaded.</h1>
        <p className="mt-5 text-[15px] font-light leading-[1.8] text-white/70">{message}</p>
        <div className="mt-8 flex gap-8 text-[12px] uppercase tracking-[0.3em]">
          <button type="button" onClick={onRetry} className="border-b border-white pb-1">
            Try again
          </button>
          <Link to="/gallery" className="border-b border-white/40 pb-1 text-white/75 hover:text-white">
            Gallery
          </Link>
        </div>
      </div>
    </main>
  )
}
